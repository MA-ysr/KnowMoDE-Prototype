package org.xaikg.mde;

import java.nio.file.Files;
import java.nio.file.Path;
import java.time.Instant;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;

import org.eclipse.emf.common.util.URI;
import org.eclipse.emf.ecore.resource.Resource;
import org.eclipse.emf.ecore.resource.ResourceSet;
import org.eclipse.emf.ecore.resource.impl.ResourceSetImpl;
import org.eclipse.epsilon.emc.emf.InMemoryEmfModel;
import org.eclipse.epsilon.eol.models.IModel;

/** T5: ValidatedKG model(s) -> Cypher loader script (paper, Phase 4). */
public final class Loader {

    static final String T5_FILE = "t5_loader.egl";

    private Loader() {}

    public static void run(MdeHome home, ModelSet ms, Path validated, Path out, Map<String, Object> report) throws Exception {
        if (!ms.has("Schema")) throw new IllegalArgumentException("T5 needs the KG Schema model");
        ResourceSet rs = new ResourceSetImpl();
        Resource first = null;
        List<Path> files = new ArrayList<>();
        List<Path> candidates = new ArrayList<>();
        if (Files.isDirectory(validated)) {
            try (var walk = Files.walk(validated)) {
                walk.filter(f -> f.getFileName().toString().endsWith(".xmi")).sorted().forEach(candidates::add);
            }
        } else {
            candidates.add(validated);
        }
        for (Path p : candidates) {
            Resource r = rs.getResource(URI.createFileURI(p.toAbsolutePath().toString()), true);
            if (!r.getContents().isEmpty() && r.getContents().get(0).eClass().getName().equals("ValidatedKG")) {
                if (first == null) first = r;
                files.add(p);
            }
        }
        if (first == null) throw new IllegalArgumentException("No validated-kg .xmi under " + validated);
        InMemoryEmfModel vkg = new InMemoryEmfModel("VKG", first, List.of(ms.metamodels().byNsUri(Metamodels.VALIDATED_NS)));
        vkg.setExpand(true);
        IModel schema = Validation.model(ms, "Schema");
        var schemaRoot = ms.resource("Schema").getContents().get(0);
        String body = Epsilon.runEgl(home.transformations().resolve(T5_FILE), List.of(vkg, schema),
            Map.of("ids", new Ids(), "schema", schemaRoot));
        vkg.dispose();
        StringBuilder sb = new StringBuilder();
        sb.append("// Generated by xaikg-mde (T2 -> T5). DO NOT EDIT: regenerate from the validated KG model.\n");
        sb.append("// generated-at: ").append(Instant.now()).append('\n');
        for (Path f : files) sb.append("// input: ").append(f.getFileName()).append(" sha256=").append(Hashing.sha256(f)).append('\n');
        for (var e : ms.fingerprints().entrySet()) sb.append("// input: ").append(e.getKey()).append(" sha256=").append(e.getValue()).append('\n');
        sb.append(body);
        Files.createDirectories(out.toAbsolutePath().getParent());
        Files.writeString(out, sb.toString());
        report.put("status", "ok");
        report.put("output", out.toAbsolutePath().toString());
        report.put("validatedFiles", files.stream().map(Path::toString).toList());
        report.put("statements", body.lines().filter(l -> l.endsWith(";")).count());
        report.put("sourceModels", ms.fingerprints());
    }
}
