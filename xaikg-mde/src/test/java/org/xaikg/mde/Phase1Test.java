package org.xaikg.mde;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.nio.file.Files;
import java.nio.file.Path;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.condition.EnabledIf;

/**
 * Phase 1 acceptance: the healthcare M1 models satisfy C1-C5, the generation chain T1/T3/T4 runs,
 * and every injected fault of the E2 mutation set is blocked by the constraint layer.
 * Runs against the repository layout (implementation/models), so it is skipped when the models
 * are not present (e.g. when the jar is built elsewhere).
 */
class Phase1Test {

    static final Path IMPL = Path.of("..").toAbsolutePath().normalize();
    static final Path MODELS = IMPL.resolve("models/diabetes-readmission");
    static final Path MUTANTS = IMPL.resolve("models/mutants");
    static MdeHome home;
    static Metamodels metamodels;

    static boolean modelsPresent() {
        return Files.isDirectory(MODELS);
    }

    @BeforeAll
    static void setUp() throws Exception {
        home = MdeHome.resolve(Path.of(".").toAbsolutePath().normalize());
        metamodels = Metamodels.registerAll(home);
    }

    @Test
    @EnabledIf("modelsPresent")
    void healthcareModelsSatisfyAllBlockingConstraints() throws Exception {
        try (ModelSet ms = ModelSet.load(metamodels, List.of(MODELS))) {
            Map<String, Object> report = new LinkedHashMap<>();
            int code = Commands.runCheck(home, ms, false, report);
            assertEquals(Main.EXIT_OK, code, () -> "check failed: " + Json.write(report));
            assertTrue(ms.unresolved().isEmpty(), "all cross-file references resolve");
            assertEquals(5, ms.loaded().size(), "five M1 models");
        }
    }

    @Test
    @EnabledIf("modelsPresent")
    void generationChainProducesDdlAndPrompts() throws Exception {
        Path out = Files.createTempDirectory("xaikg-gen-");
        try (ModelSet ms = ModelSet.load(metamodels, List.of(MODELS))) {
            Map<String, Object> t1 = new LinkedHashMap<>();
            Commands.runT1(home, ms, out.resolve("graph-schema.xmi"), t1);
            @SuppressWarnings("unchecked")
            Map<String, Object> counts = (Map<String, Object>) t1.get("counts");
            assertEquals(9, counts.get("nodeLabels"), "7 concepts + 2 provenance labels");
            assertTrue((int) counts.get("relationshipTypes") >= 14);

            Map<String, Object> t3 = new LinkedHashMap<>();
            Commands.runT3(home, out.resolve("graph-schema.xmi"), out.resolve("schema.cypher"), Map.of(), t3);
            String ddl = Files.readString(out.resolve("schema.cypher"));
            assertTrue(ddl.contains("CREATE CONSTRAINT drug_name_unique IF NOT EXISTS"));
            assertTrue(ddl.contains("FOR (n:SourceDocument) REQUIRE n.id IS UNIQUE"));

            Map<String, Object> t4 = new LinkedHashMap<>();
            Commands.runT4(home, ms, out, t4);
            String prompt = Files.readString(out.resolve("prompts/drug_label_extraction.txt"));
            assertTrue(prompt.contains("## Drug"), "prompt lists the targeted concepts");
            assertTrue(prompt.contains("- MAY_CAUSE: Drug -> Condition"), "prompt lists relations with endpoints");
            assertFalse(prompt.contains("## Recommendation"), "prompt is limited to the task's targets (C2)");
            assertTrue(Files.exists(out.resolve("prompts/prompt-registry.json")));
        }
    }

    @Test
    @EnabledIf("modelsPresent")
    void everyMutantIsBlockedBeforeGeneration() throws Exception {
        if (!Files.isDirectory(MUTANTS)) {
            return; // mutants are generated by xaikg-pipeline/tools/make_mutants.py
        }
        try (var dirs = Files.list(MUTANTS)) {
            for (Path mutant : (Iterable<Path>) dirs.filter(Files::isDirectory).sorted()::iterator) {
                try (ModelSet ms = ModelSet.load(metamodels, List.of(mutant))) {
                    Map<String, Object> report = new LinkedHashMap<>();
                    int code = Commands.runCheck(home, ms, false, report);
                    assertEquals(Main.EXIT_MODEL_INVALID, code,
                        () -> mutant.getFileName() + " was NOT blocked: " + Json.write(report));
                }
            }
        }
    }
}
